cars = ["tata","suzuki","bmw"]
print(cars)

# using range in array 
# ex:-
cars =  ["tata","suzuki","bmw"]
for car in cars:
    print(car)


# finding length of variable 
# ex:-
cars =  ["tata","suzuki","bmw"]
print(len(cars))

# changing value in array
# ex:-
cars =  ["tata","suzuki","bmw"]
cars[1] = "volvo"
print(cars)

